import fs from 'node:fs/promises';
import path from 'node:path';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { Compass, Target, Gem, MessagesSquare, BadgeCheck, ClipboardList, FileCheck2, HeartPulse, House, LifeBuoy, Mail, Plane, ShieldCheck, Users, BriefcaseBusiness, CircleHelp, SlidersHorizontal, RefreshCw, Car, Building2, Layers, Check, Wallet, Ship } from 'lucide-react';
import { topics } from '../site/assets/js/page-topics.js';

// Reuse the site's installed Lucide icons; the public module has no dependency.
function symbolFor(label) {
  const rules = [
    [/vision/i, Compass], [/mission/i, Target], [/values/i, Gem],
    [/verification|confirm/i, BadgeCheck], [/conversation|talk/i, MessagesSquare],
    [/money|fidelity/i, Wallet], [/tailor/i, SlidersHorizontal], [/liability|work injury/i, ShieldCheck],
    [/marine|cargo/i, Ship], [/email/i, Mail], [/question/i, CircleHelp], [/compare|decisions|options|limits/i, SlidersHorizontal],
    [/changed|updates|renewal|year|continuity/i, RefreshCw], [/vehicle|motor/i, Car],
    [/home|property|protect|owner|tenant/i, House], [/industry|business|projects/i, Building2],
    [/travel|trip|marine/i, Plane], [/^Domestic helper$/i, Users], [/claim|help|support/i, LifeBuoy],
    [/^Lifestyle cover$/i, Layers], [/^Domestic helper$|^Personal accident$/i, Users],
    [/medical|benefit|cover/i, HeartPulse], [/employee|people|hr|personal/i, Users],
    [/services|activities/i, BriefcaseBusiness], [/documents|details|requirements|duties|declarations/i, FileCheck2],
    [/brief|steps|prepare|gather/i, ClipboardList], [/tools|programme|specialist/i, Layers],
  ];
  return rules.find(([pattern]) => pattern.test(label))?.[1] || ShieldCheck;
}

export async function writeNavigatorIcons(root) {
  const render = component => renderToStaticMarkup(createElement(component, {
    width: 24, height: 24, strokeWidth: 1.65, 'aria-hidden': true, focusable: false,
  }));
  const labels = [...new Set(Object.values(topics).flat())];
  const symbols = Object.fromEntries(labels.map(label => [label, render(symbolFor(label))]));
  const module = '// Generated by scripts/design-navigators.mjs using existing Lucide icons (ISC).\n'
    + `export const topicIcons = ${JSON.stringify(symbols,null,2)};\n`
    + `export const selectedIcon = ${JSON.stringify(render(Check))};\n`;
  await fs.writeFile(path.join(root,'assets/js/page-topic-icons.js'),module);
}
